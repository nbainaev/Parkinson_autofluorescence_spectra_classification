import json

import numpy as np
import pandas as pd
import pytest

from spectra_ml.blinding import load_blinded_test_manifest
from spectra_ml.integrity import IntegrityError, verify_manifest, write_manifest
from spectra_ml.splitting import patient_level_holdout_split


def test_blinded_manifest_rejects_label_or_real_id(tmp_path):
    path = tmp_path / "blind.csv"
    pd.DataFrame({"study_id": ["S1"], "target": [1]}).to_csv(path, index=False)
    with pytest.raises(ValueError, match="unexpectedly contains"):
        load_blinded_test_manifest(path)


def test_prediction_identity_lookup_is_target_free():
    path = "outputs/final_study/private/prediction_identity_lookup.csv"
    if not __import__("os").path.exists(path):
        pytest.skip("identity lookup is generated by prepare_blinded_study.py")
    assert "target" not in pd.read_csv(path, nrows=1).columns


def test_patient_holdout_has_no_patient_overlap():
    pid = np.repeat([f"p{i}" for i in range(20)], 2)
    y = np.repeat([0] * 10 + [1] * 10, 2).astype(float)
    dev, test = patient_level_holdout_split(pid, y, .2, 42)
    assert set(pid[dev]).isdisjoint(pid[test])
    assert set(np.unique(y[test])) == {0.0, 1.0}


def test_manifest_detects_tampering(tmp_path):
    artifact = tmp_path / "model.bin"
    artifact.write_bytes(b"frozen")
    manifest = tmp_path / "manifest.json"
    write_manifest([str(artifact)], str(manifest), base_dir=str(tmp_path))
    verify_manifest(str(manifest), base_dir=str(tmp_path))
    artifact.write_bytes(b"changed")
    with pytest.raises(IntegrityError, match="HASH MISMATCH"):
        verify_manifest(str(manifest), base_dir=str(tmp_path))
